// The browser runtime is webpack-dev-middleware's. This writes the files that
// used to be built from `client-src/`, each one re-exporting the middleware's,
// so every `webpack-dev-server/client/...` import keeps resolving to the same
// thing it always did — now one implementation rather than two.
//
// Generated rather than committed because there is no client source here any
// more, and a re-export checked into the repository is still a client file to
// keep in step with the middleware.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const clientDir = path.join(root, "client");

// Where each published path now comes from. Only the paths that have an
// equivalent are kept: the rest of what `client-src/` built — the socket
// wrapper, the log and sendMessage helpers, the bundled logger — were this
// client's own internals, and the middleware's client has its own.
const SHIMS = {
  // The runtime itself: what `entry` pointed at, and what the middleware now
  // injects for us. Re-exported so a configuration that lists it by hand, or
  // anything importing it for `setOptionsAndConnect`, still works.
  "index.js": "webpack-dev-middleware/client",
  // The overlay, which other tooling imports directly. The middleware's is
  // the superset of the two, and keeps this project's element id when this
  // server configures it.
  "overlay.js": "webpack-dev-middleware/client/overlay",
  // The progress indicator, named `indicator` there.
  "progress.js": "webpack-dev-middleware/client/indicator",
  // What `client.webSocketTransport` resolves to for each built-in transport,
  // and what a transport of someone else's extends.
  "clients/WebSocketClient.js": "webpack-dev-middleware/client/ws",
  "clients/EventSourceClient.js": "webpack-dev-middleware/client/sse",
};

/**
 * @param {string} from the published path
 * @param {string} to the module it now comes from
 * @returns {string} the file to write
 */
function shim(from, to) {
  return `// Generated by scripts/build-client.mjs — do not edit.
//
// \`webpack-dev-server/client/${from}\` is webpack-dev-middleware's client.
// See the "the browser runtime moved" note in the changelog.
module.exports = require("${to}");
`;
}

/**
 * The runtime is the one module that is written into `entry` with a query,
 * and the query is on this file rather than on the middleware's. It is handed
 * over before the runtime is required, because the runtime reads its options
 * and connects as it is evaluated.
 * @param {string} from the published path
 * @param {string} to the module it now comes from
 * @returns {string} the file to write
 */
function runtimeShim(from, to) {
  return `// Generated by scripts/build-client.mjs — do not edit.
//
// \`webpack-dev-server/client/${from}\` is webpack-dev-middleware's client.
// See the "the browser runtime moved" note in the changelog.
/* global __resourceQuery */
if (typeof __resourceQuery === "string" && __resourceQuery.length > 0) {
  self.__webpack_dev_middleware_client_query__ = __resourceQuery;
}

module.exports = require("${to}");
`;
}

await fs.rm(clientDir, { recursive: true, force: true });
await fs.mkdir(clientDir, { recursive: true });

// This package is a module, and a module has no `module` or `require`. The
// runtime's stand-in needs both, to hand its query over before the runtime
// evaluates, so this folder is CommonJS. webpack still reads the middleware's
// ES modules through `require`, with their exports intact.
await fs.writeFile(
  path.join(clientDir, "package.json"),
  `${JSON.stringify({ type: "commonjs" }, null, 2)}\n`,
);

for (const [from, to] of Object.entries(SHIMS)) {
  const file = path.join(clientDir, from);

  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(
    file,
    from === "index.js" ? runtimeShim(from, to) : shim(from, to),
  );
}

// eslint-disable-next-line no-console
console.log(
  `client: wrote ${Object.keys(SHIMS).length} re-exports of webpack-dev-middleware's client`,
);
